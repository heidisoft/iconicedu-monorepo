import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const result = await build({
  entryPoints: [path.join(root, 'src/components/classroom/canvas/entry.tsx')],
  alias: { '@iconicedu/utils': path.resolve(root, '../../packages/utils/src/index.ts') },
  bundle: true,
  conditions: ['production'],
  write: false,
  outdir: 'canvas',
  minify: true,
  define: { 'process.env.NODE_ENV': '"production"' },
  loader: { '.woff2': 'dataurl', '.woff': 'dataurl', '.ttf': 'dataurl' },
});
let js = result.outputFiles.find((file) => file.path.endsWith('.js')).text;
// Bundle Latin drawing fonts offline. CJK glyphs use the device system fallback;
// embedding hundreds of CJK subsets in the JS bundle overwhelms Metro and tablets.
const fontsRoot = path.resolve(
  root,
  '../../node_modules/@excalidraw/excalidraw/dist/prod/fonts',
);
js = js.replace(/(["'])\.\/fonts\/([^"']+\.woff2)\1/g, (_match, _quote, relative) => {
  if (relative.startsWith('Xiaolai/')) return JSON.stringify('data:font/woff2;base64,');
  const file = path.resolve(fontsRoot, relative);
  if (!file.startsWith(fontsRoot + path.sep))
    throw new Error('Invalid bundled font path');
  return JSON.stringify(
    `data:font/woff2;base64,${fs.readFileSync(file).toString('base64')}`,
  );
});
const css = result.outputFiles.find((file) => file.path.endsWith('.css'))?.text ?? '';
const html = `<!doctype html><html><head><meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data: blob:; font-src data:; connect-src data:"><style>html,body,#root{margin:0;width:100%;height:100%;overscroll-behavior:none}${css}</style></head><body><div id="root"></div><script>${js.replaceAll('</script', '<\\/script')}</script></body></html>`;
const output = path.join(root, 'src/components/classroom/canvas/canvas.generated.ts');
fs.writeFileSync(
  output,
  `// Generated by scripts/build-classroom-canvas.mjs; do not edit.\nexport const classroomCanvasHtml = ${JSON.stringify(html)};\n`,
);
console.log('Built offline classroom canvas');
